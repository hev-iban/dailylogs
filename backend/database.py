"""PostgreSQL connection and schema."""
from contextlib import closing
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row

from models import DEFAULT_LIST_LIMIT, MAX_LIST_LIMIT, MAX_LIST_OFFSET

SCHEMA = """
CREATE TABLE IF NOT EXISTS logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS photos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id INTEGER NOT NULL REFERENCES logs(id) ON DELETE CASCADE,
    path TEXT NOT NULL,
    position INTEGER NOT NULL
);
"""


def connect(database_url: str) -> psycopg.Connection:
    """Open a connection (autocommit off); rows are dicts, so row["col"] works."""
    return psycopg.connect(database_url, row_factory=dict_row)


def _fmt(value: datetime) -> str:
    """UTC ISO-8601 with six fractional digits and +00:00, whatever the session TimeZone."""
    return value.astimezone(timezone.utc).isoformat(timespec="microseconds")


def _migrate_timestamps(conn: psycopg.Connection) -> None:
    """Convert logs.created_at / updated_at from TEXT to TIMESTAMPTZ, all or nothing.

    Runs in the caller's transaction (the caller commits). The table is locked first so a
    concurrently starting instance waits and then finds the columns already converted.
    The session zone is UTC for the casts, so offsetless legacy text reads as UTC.
    Only columns still TEXT are altered.
    """
    conn.execute("LOCK TABLE logs IN ACCESS EXCLUSIVE MODE")
    text_cols = [r["column_name"] for r in conn.execute(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = 'logs' "
        "AND column_name IN ('created_at', 'updated_at') AND data_type = 'text' "
        "ORDER BY column_name")]
    if not text_cols:
        return
    conn.execute("SET LOCAL TimeZone = 'UTC'")
    for col in text_cols:  # fixed names from the query above, never user input
        conn.execute(
            f"ALTER TABLE logs ALTER COLUMN {col} TYPE TIMESTAMPTZ USING {col}::timestamptz")


def init_db(database_url: str) -> None:
    with closing(connect(database_url)) as conn:
        try:
            conn.execute(SCHEMA)
            _migrate_timestamps(conn)
            conn.commit()
        except psycopg.Error as exc:
            conn.rollback()
            raise RuntimeError(
                "database migration failed: could not convert logs.created_at / "
                "logs.updated_at from TEXT to TIMESTAMPTZ (a value is not a valid "
                f"timestamp?). No data was changed. Details: {exc}") from exc


def list_logs(conn: psycopg.Connection, limit: int = DEFAULT_LIST_LIMIT,
              offset: int = 0) -> list[dict]:
    """One page of logs, newest first (ties: higher id first), photos in upload order.

    Skips the `offset` newest logs. limit is clamped to 1..MAX_LIST_LIMIT and offset to
    0..MAX_LIST_OFFSET. Photo rows are read only for the returned logs.
    """
    limit = max(1, min(limit, MAX_LIST_LIMIT))
    offset = max(0, min(offset, MAX_LIST_OFFSET))
    logs = conn.execute(
        "SELECT id, description, created_at, updated_at FROM logs "
        "ORDER BY created_at DESC, id DESC LIMIT %s OFFSET %s",
        (limit, offset),
    ).fetchall()
    photos: dict[int, list[str]] = {}
    if logs:
        for row in conn.execute(
            "SELECT log_id, path FROM photos WHERE log_id = ANY(%s) ORDER BY position, id",
            ([r["id"] for r in logs],),
        ):
            photos.setdefault(row["log_id"], []).append(row["path"])
    return [
        {
            "id": r["id"],
            "description": r["description"],
            "photos": photos.get(r["id"], []),
            "created_at": _fmt(r["created_at"]),
            "updated_at": _fmt(r["updated_at"]),
        }
        for r in logs
    ]


def insert_log(conn: psycopg.Connection, description: str,
               photo_paths: list[str], now: datetime) -> dict:
    """Insert a log and its photos. Does not commit; the caller owns the transaction."""
    cur = conn.execute(
        "INSERT INTO logs (description, created_at, updated_at) VALUES (%s, %s, %s) RETURNING id",
        (description, now, now),
    )
    log_id = cur.fetchone()["id"]
    conn.cursor().executemany(
        "INSERT INTO photos (log_id, path, position) VALUES (%s, %s, %s)",
        [(log_id, p, i) for i, p in enumerate(photo_paths)],
    )
    return {
        "id": log_id,
        "description": description,
        "photos": list(photo_paths),
        "created_at": _fmt(now),
        "updated_at": _fmt(now),
    }


def get_log(conn: psycopg.Connection, log_id: int) -> dict | None:
    """One log in the list_logs shape, or None if the id is unknown."""
    row = conn.execute(
        "SELECT id, description, created_at, updated_at FROM logs WHERE id = %s",
        (log_id,),
    ).fetchone()
    if row is None:
        return None
    paths = [r["path"] for r in conn.execute(
        "SELECT path FROM photos WHERE log_id = %s ORDER BY position, id", (log_id,))]
    return {
        "id": row["id"],
        "description": row["description"],
        "photos": paths,
        "created_at": _fmt(row["created_at"]),
        "updated_at": _fmt(row["updated_at"]),
    }


def lock_log(conn: psycopg.Connection, log_id: int) -> bool:
    """Take the row lock on a log (SELECT ... FOR UPDATE); False if the id is unknown.

    Blocks while another transaction holds the row. The lock lasts until the caller's
    commit or rollback. Run it as the first statement of the transaction, before reading
    the photo rows. Does not commit; the caller owns the transaction.
    """
    row = conn.execute("SELECT id FROM logs WHERE id = %s FOR UPDATE", (log_id,)).fetchone()
    return row is not None


def delete_log(conn: psycopg.Connection, log_id: int) -> list[str] | None:
    """Delete a log; its photo rows go with it (ON DELETE CASCADE).

    Returns the deleted photo paths in upload order, or None if the id is unknown.
    Does not commit; the caller owns the transaction.
    """
    paths = [r["path"] for r in conn.execute(
        "SELECT path FROM photos WHERE log_id = %s ORDER BY position, id", (log_id,))]
    cur = conn.execute("DELETE FROM logs WHERE id = %s", (log_id,))
    if cur.rowcount == 0:
        return None
    return paths


def update_log(conn: psycopg.Connection, log_id: int, description: str,
               photo_paths: list[str], now: datetime) -> dict | None:
    """Set description/updated_at and replace the photo rows with photo_paths, in order.

    Does not commit; the caller owns the transaction. None if the id is unknown.
    """
    cur = conn.execute(
        "UPDATE logs SET description = %s, updated_at = %s WHERE id = %s",
        (description, now, log_id),
    )
    if cur.rowcount == 0:
        return None
    conn.execute("DELETE FROM photos WHERE log_id = %s", (log_id,))
    conn.cursor().executemany(
        "INSERT INTO photos (log_id, path, position) VALUES (%s, %s, %s)",
        [(log_id, p, i) for i, p in enumerate(photo_paths)],
    )
    return get_log(conn, log_id)
