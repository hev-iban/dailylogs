"""TEXT -> TIMESTAMPTZ migration, UTC output format and chronological ordering (test DB only)."""
import os

import psycopg
import pytest

import database
from conftest import execute_sql, make_log, rows

FMT_LEN = len("2026-01-01T00:00:00.000000+00:00")


def _types(db):
    with psycopg.connect(db) as conn:
        return dict(conn.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_name = 'logs' AND column_name IN ('created_at', 'updated_at')"
        ).fetchall())


def _make_text_schema(db, values):
    """Recreate logs/photos with TEXT timestamps in the test DB; values = [(created, updated)]."""
    execute_sql(db, "DROP TABLE IF EXISTS photos, logs CASCADE")
    execute_sql(db, "CREATE TABLE logs (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "description TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)")
    execute_sql(db, "CREATE TABLE photos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "log_id INTEGER NOT NULL REFERENCES logs(id) ON DELETE CASCADE, "
                    "path TEXT NOT NULL, position INTEGER NOT NULL)")
    for i, (c, u) in enumerate(values):
        execute_sql(db, "INSERT INTO logs (description, created_at, updated_at) VALUES (%s, %s, %s)",
                    (f"d{i}", c, u))
        execute_sql(db, "INSERT INTO photos (log_id, path, position) VALUES (%s, %s, 0)",
                    (i + 1, f"/uploads/{i}.png"))


@pytest.fixture
def text_schema(test_url):
    yield lambda values: _make_text_schema(test_url, values)
    # leave the schema as the fixtures expect
    execute_sql(test_url, "DROP TABLE IF EXISTS photos, logs CASCADE")
    database.init_db(test_url)


def _as_utc(db, col):
    with psycopg.connect(db) as conn:
        conn.execute("SET TimeZone = 'UTC'")
        return [r[0].isoformat() for r in conn.execute(f"SELECT {col} FROM logs ORDER BY id")]


def test_fresh_schema_is_timestamptz(test_url):
    assert _types(test_url) == {"created_at": "timestamp with time zone",
                                "updated_at": "timestamp with time zone"}


def test_migration_converts_and_preserves(test_url, text_schema):
    text_schema([("2026-01-01T10:00:00.000000+05:00", "2026-01-02T00:00:00+00:00"),
                 ("2026-01-01T06:00:00.123456+00:00", "2026-01-01T06:00:00.123456+00:00")])
    assert set(_types(test_url).values()) == {"text"}
    database.init_db(test_url)
    assert set(_types(test_url).values()) == {"timestamp with time zone"}
    logs, photos = rows(test_url)
    assert len(logs) == 2 and len(photos) == 2
    assert [x["description"] for x in logs] == ["d0", "d1"]
    assert _as_utc(test_url, "created_at") == ["2026-01-01T05:00:00+00:00",
                                               "2026-01-01T06:00:00.123456+00:00"]
    assert _as_utc(test_url, "updated_at")[0] == "2026-01-02T00:00:00+00:00"


def test_migration_idempotent(test_url, text_schema):
    text_schema([("2026-01-01T10:00:00+05:00", "2026-01-01T10:00:00+05:00")])
    database.init_db(test_url)
    before = rows(test_url)
    database.init_db(test_url)
    database.init_db(test_url)
    assert rows(test_url) == before
    assert set(_types(test_url).values()) == {"timestamp with time zone"}


def test_migration_only_converts_text_column(test_url, text_schema):
    text_schema([("2026-01-01T10:00:00+05:00", "2026-01-01T10:00:00+05:00")])
    execute_sql(test_url, "ALTER TABLE logs ALTER COLUMN updated_at TYPE TIMESTAMPTZ "
                          "USING updated_at::timestamptz")
    database.init_db(test_url)
    assert set(_types(test_url).values()) == {"timestamp with time zone"}


def test_migration_empty_table(test_url, text_schema):
    text_schema([])
    database.init_db(test_url)
    assert set(_types(test_url).values()) == {"timestamp with time zone"}


@pytest.mark.parametrize("bad_col", ["created_at", "updated_at"])
def test_bad_value_aborts_and_changes_nothing(test_url, text_schema, bad_col):
    good = "2026-01-01T10:00:00+05:00"
    text_schema([(good, good), (good, good)])
    execute_sql(test_url, f"UPDATE logs SET {bad_col} = 'not a date' WHERE id = 2")
    before = rows(test_url)
    with pytest.raises(RuntimeError, match="migration failed"):
        database.init_db(test_url)
    assert set(_types(test_url).values()) == {"text"}
    assert rows(test_url) == before


def test_empty_string_value_aborts(test_url, text_schema):
    text_schema([("2026-01-01T10:00:00+00:00", "")])
    with pytest.raises(RuntimeError):
        database.init_db(test_url)
    assert set(_types(test_url).values()) == {"text"}


def test_offsetless_legacy_value_is_utc_under_other_zone(test_url, text_schema):
    text_schema([("2026-01-01T10:00:00", "2026-01-01T10:00:00"),
                 ("2026-01-01T10:00:00+00:00", "2026-01-01T10:00:00+00:00")])
    # init_db opens its own connection; force a non-UTC session zone through PGOPTIONS
    old = os.environ.get("PGOPTIONS")
    os.environ["PGOPTIONS"] = "-c TimeZone=Asia/Tokyo"
    try:
        database.init_db(test_url)
    finally:
        if old is None:
            del os.environ["PGOPTIONS"]
        else:
            os.environ["PGOPTIONS"] = old
    a, b = _as_utc(test_url, "created_at")
    assert a == b == "2026-01-01T10:00:00+00:00"


@pytest.mark.parametrize("zone", ["Asia/Tokyo", "America/New_York"])
def test_response_format_under_non_utc_zone(env, monkeypatch, zone):
    client, db, _ = env
    monkeypatch.setenv("PGOPTIONS", f"-c TimeZone={zone}")
    log = make_log(client, 1)
    got = client.get("/api/logs").json()[0]
    for key in ("created_at", "updated_at"):
        assert log[key] == got[key]
        assert got[key].endswith("+00:00") and len(got[key]) == FMT_LEN and "." in got[key]
    edited = client.put(f"/api/logs/{log['id']}", data={"description": "e", "remove_photos": []}).json()
    assert edited["created_at"] == log["created_at"]
    assert edited["updated_at"] == client.get("/api/logs").json()[0]["updated_at"]
    assert edited["updated_at"].endswith("+00:00")


def test_zero_microseconds_still_rendered(env):
    client, db, _ = env
    log = make_log(client, 1)
    execute_sql(db, "UPDATE logs SET created_at = '2026-01-01T00:00:00+00:00'")
    assert client.get("/api/logs").json()[0]["created_at"] == "2026-01-01T00:00:00.000000+00:00"
    assert log["id"]


def test_ordering_is_chronological_across_offsets(env):
    client, db, _ = env
    a = make_log(client, 1)["id"]
    b = make_log(client, 1)["id"]
    c = make_log(client, 1)["id"]
    # text order and time order disagree: a = 05:00 UTC (earliest), b = 06:00 UTC
    execute_sql(db, "UPDATE logs SET created_at = '2026-01-01T10:00:00+05:00' WHERE id = %s", (a,))
    execute_sql(db, "UPDATE logs SET created_at = '2026-01-01T06:00:00+00:00' WHERE id = %s", (b,))
    # c has the same instant as b, expressed with another offset; higher id wins the tie
    execute_sql(db, "UPDATE logs SET created_at = '2026-01-01T01:00:00-05:00' WHERE id = %s", (c,))
    assert [x["id"] for x in client.get("/api/logs").json()] == [c, b, a]
